#[serde(rename_all = "snake_case")]
pub struct CameraData {
    pub target: Option<Point>,
    pub laser: Option<Point>,
}

/// Maintains a persistent bidirectional WebSocket connection with Ground Control (GC).
///
/// This asynchronous task is responsible for multiplexing incoming network commands
/// and outgoing system telemetry over a single WebSocket connection. It is designed
/// to be highly resilient, featuring automatic connection retries and a ping/pong
/// watchdog to detect and recover from silent network drops.
///
/// # Architecture
/// Internally, it uses a `tokio::select!` loop to concurrently handle:
/// - Forwarding internal telemetry from `telemetry_rx` to the GC.
/// - Receiving JSON commands from the GC, deserializing them, and passing them to `handle_command`.
/// - Sending periodic WebSocket `Ping` frames (every 3 seconds).
/// - Monitoring a 10-second watchdog timer that resets upon receiving a `Pong` from the GC.
///
/// If the connection is lost or the connection attempt fails, the loop will automatically
/// wait for a short duration and attempt to reconnect.
///
/// # Arguments
/// * `connect_addr` - The full WebSocket URI to connect to (e.g., `"ws://127.0.0.1:8080"`).
/// * `telemetry_rx` - An `mpsc` receiver providing a stream of `TelemetryEnvelope` packets
///   generated by various satellite subsystems.
/// * `command_tx` - An `mpsc` sender used to route parsed commands from the GC
///   down to the satellite's command arbiter.
pub async fn run_websocket_client(
    mut telemetry_rx: mpsc::Receiver<TelemetryEnvelope>,
    command_tx: mpsc::Sender<LocalCommand>,
    network_config: NetworkConfig,
) {
    let reconnect_delay = Duration::from_secs(3);
    let watchdog_duration = Duration::from_secs(10);
    let mut ping_interval = interval(Duration::from_secs(3));

    let connect_address_string = format!(
        "ws://{}:{}",
        network_config.ground_station_ip, network_config.telemetry_port
    );
    let connect_address = connect_address_string.as_str();

    loop {
        info!("Attempting to connect to GCS server at {connect_address}");

        // Attempt to connect
        let ws_stream = match connect_async(connect_address).await {
            Ok((stream, _)) => stream,
            Err(e) => {
                warn!("Connection failed: {e}. Retrying in {reconnect_delay:?}");
                sleep(reconnect_delay).await;
                continue;
            }
        };

        info!("Connected to GCS!");
        let (mut sender, mut receiver) = ws_stream.split();
        let mut watchdog = Box::pin(sleep(watchdog_duration));

        loop {
            tokio::select! {
                msg = receiver.next() => {
                    match msg {
                        Some(Ok(Message::Text(text))) => {
                            match serde_json::from_str::<CommandEnvelope>(&text) {
                                Ok(cmd) => {
                                    handle_command(cmd, &command_tx).await;
                                }
                                Err(e) => {
                                    error!("Error: {e}, command: {text}");
                                }
                            }
                        }
                        Some(Ok(Message::Close(_))) | None => {
                            warn!("Server disconnected.");
                            break; // Break the inner loop to trigger a reconnect
                        }
                        Some(Ok(Message::Pong(_))) => {
                            info!("Pong received, watchdog reset");
                            watchdog = Box::pin(sleep(watchdog_duration));
                        }
                        _ => {}
                    }
                }

                // Forward internal broadcast telemetry to the Server
                telemetry_opt = telemetry_rx.recv() => {
                    if let Some(telemetry) = telemetry_opt {
                        match serde_json::to_string(&telemetry) {
                            Ok(json) => {
                                if sender.send(Message::Text(json.into())).await.is_err() {
                                    warn!("Failed to send telemetry. Connection likely lost.");
                                    break; // Break the inner loop to trigger a reconnect
                                }
                            }
                            Err(e) => {
                                error!("Failed to serialize telemetry data: {e}");
                            }
                        }
                    } else {
                        // If the internal mpsc channel closes, the main app is shutting down
                        warn!("Internal telemetry channel closed. Shutting down client.");
                        return;
                    }
                }

                _ = ping_interval.tick() => {
                    if let Err(e) = sender.send(Message::Ping(Bytes::from(""))).await {
                        println!("Failed to send ping: {e}");
                        break;
                    }
                }


                // If the watchdog fails
                () = &mut watchdog => {
                    warn!("No ping received from GCS in 10 seconds!");
                    // Reset watchdog so it doesn't spam, or break here to force a TCP reconnect
                    watchdog = Box::pin(sleep(watchdog_duration));
                }
            }
        }

        // Wait briefly before attempting to reconnect
        sleep(reconnect_delay).await;
    }
}

pub async fn handle_command(command: CommandEnvelope, arbiter_tx: &mpsc::Sender<LocalCommand>) {
    match command {
        CommandEnvelope::Gimbal(GimbalCommands::ManualOverride { pan, tilt }) => {
            if let Err(e) = arbiter_tx
                .send(LocalCommand::ManualOverride { pan, tilt })
                .await
            {
                error!("Failed to forward manual override to Arbiter: {e}");
            } else {
                debug!("Forwarded Manual Override ({pan:.1}, {tilt:.1}) to Arbiter");
            }
        }

        CommandEnvelope::Gimbal(GimbalCommands::SetTrackingMode(enabled)) => {
            if let Err(e) = arbiter_tx
                .send(LocalCommand::SetTrackingMode(enabled))
                .await
            {
                error!("Failed to forward tracking mode to Arbiter: {e}");
            } else {
                info!("Forwarded Tracking Mode toggle ({enabled}) to Arbiter");
            }
        }

        CommandEnvelope::Gimbal(GimbalCommands::TrimPan(val)) => {
            info!("Received command to change gimbal pan by {val:1} degrees");
        }

        CommandEnvelope::Gimbal(_) => {
            warn!("Received unhandled Gimbal command");
        }

        _ => {
            debug!("Handled non-gimbal command");
        }
    }
}
